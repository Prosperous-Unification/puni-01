import { constant, object } from '@optique/core';
import {
  existsSync,
  lstatSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { join, posix } from 'node:path';
import { countWords, readWhenWordBudget } from '../budgets';
import { parseFrontMatter } from '../front-matter';
import { compareBytes, listFiles, listMarkdownFiles, RepositoryDefect } from '../repository';
import { findRepository, type Repository } from '../registry';

/** `wiki index`: rewrites `wiki/index/` from the repository's projects, pages and commands. */
export const wikiIndexParser = object({ kind: constant('wiki index') });

/** One command of the CLI tree: its full canonical path, such as `puni burokrat`, and brief. */
export interface CommandBrief {
  readonly path: string;
  readonly brief: string;
}

/** What `wiki index` needs from the app that composes it. */
export interface WikiIndexContext {
  /** Where the repository search starts. */
  readonly cwd: string;
  /** Every command of the composed CLI; the burokrat library cannot see the whole tree. */
  readonly commands: readonly CommandBrief[];
  readonly stdout: (text: string) => void;
  readonly stderr: (text: string) => void;
}

/** The generated directory, relative to the repository root. */
export const indexDirectory = 'wiki/index';

/** The one generated file, relative to the repository root. */
export const indexFile = `${indexDirectory}/index.md`;

const notice = '<!-- Generated by `puni burokrat wiki index`. Do not edit. -->';

/**
 * One input of the index that is missing or invalid, named by its repository path. `topic` says
 * which check reports it: `read-first` for a project's `readFirst`, `read-when` for the rest.
 */
export interface SourceDefect {
  readonly topic: 'read-when' | 'read-first';
  readonly path: string;
  readonly message: string;
}

/** One line of the "Read when" section: a project or an authored page. */
interface ReadWhenEntry {
  readonly name: string;
  readonly path: string;
  readonly readWhen: string;
}

/** Everything the index is built from, with every defect found while reading it. */
export interface IndexSources {
  readonly entries: readonly ReadWhenEntry[];
  readonly defects: readonly SourceDefect[];
}

/**
 * Why `text` cannot complete "Read this when …", or `undefined` when it can: it must start with a
 * lower-case letter, end without a full stop, stay on one line and hold at most
 * {@link readWhenWordBudget} words.
 */
function judgeReadWhen(text: string): string | undefined {
  if (!/^\p{Ll}/u.test(text)) return 'must start with a lower-case letter';
  if (text.endsWith('.')) return 'must not end with a full stop';
  if (/[\r\n]/u.test(text)) return 'must be one line';
  const words = countWords(text);
  if (words > readWhenWordBudget) {
    return `has ${String(words)} words; at most ${String(readWhenWordBudget)}`;
  }
  return undefined;
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

type Reading = { readonly entry: ReadWhenEntry } | { readonly defect: SourceDefect };

function defectOf(path: string, message: string): Reading {
  return { defect: { topic: 'read-when', path, message } };
}

/**
 * Why `readFirst` cannot name the file to read first in the project at `directory`, or
 * `undefined` when it can: a relative path that stays inside the project and names an existing
 * regular file (not a symlink).
 */
function judgeReadFirst(root: string, directory: string, readFirst: string): string | undefined {
  if (posix.isAbsolute(readFirst) || /^[A-Za-z]:|\\/u.test(readFirst)) {
    return 'must be a relative POSIX path';
  }
  const inside = posix.relative(directory, posix.join(directory, readFirst));
  if (inside === '' || inside === '..' || inside.startsWith('../')) {
    return 'must stay inside the project';
  }
  let isFile: boolean;
  try {
    isFile = lstatSync(join(root, directory, inside)).isFile();
  } catch (cause) {
    if (cause instanceof Error && 'code' in cause && cause.code === 'ENOENT') {
      return 'names a missing file';
    }
    throw cause;
  }
  return isFile ? undefined : 'must name a regular file';
}

/**
 * Reads one `project.json`: its `name`, `metadata.readWhen` and `metadata.readFirst`. Returns the
 * project's index entry, or one defect per invalid field.
 */
function readProject(root: string, path: string): Reading[] {
  let parsed: unknown;
  try {
    parsed = JSON.parse(readFileSync(join(root, path), 'utf8'));
  } catch (cause) {
    if (!(cause instanceof SyntaxError)) throw cause;
    return [defectOf(path, `is not valid JSON: ${cause.message}`)];
  }
  if (!isRecord(parsed)) return [defectOf(path, 'is not a JSON object')];
  const name = parsed['name'];
  if (typeof name !== 'string' || name === '') return [defectOf(path, 'has no name')];
  const metadata = isRecord(parsed['metadata']) ? parsed['metadata'] : {};
  const directory = posix.dirname(path);
  const defects: Reading[] = [];
  const readWhen = metadata['readWhen'];
  if (typeof readWhen !== 'string' || readWhen === '') {
    defects.push(defectOf(path, `project ${name} has no metadata.readWhen`));
  } else {
    const problem = judgeReadWhen(readWhen);
    if (problem !== undefined) {
      defects.push(defectOf(path, `project ${name} metadata.readWhen ${problem}`));
    }
  }
  const readFirst = metadata['readFirst'];
  const readFirstProblem =
    typeof readFirst !== 'string' || readFirst === ''
      ? 'is missing'
      : judgeReadFirst(root, directory, readFirst);
  if (readFirstProblem !== undefined) {
    const message = `project ${name} metadata.readFirst ${readFirstProblem}`;
    defects.push({ defect: { topic: 'read-first', path, message } });
  }
  if (defects.length > 0 || typeof readWhen !== 'string' || typeof readFirst !== 'string') {
    return defects;
  }
  return [{ entry: { name, path: posix.join(directory, readFirst), readWhen } }];
}

/**
 * The `title` and `read-when` of an authored page, from front matter that opens the file between
 * two `---` lines and holds one `key: value` per line.
 */
function readPage(path: string, text: string): Reading {
  const frontMatter = parseFrontMatter(text);
  if ('problem' in frontMatter) {
    return defectOf(
      path,
      frontMatter.problem === 'absent'
        ? 'does not begin with front matter'
        : `has a malformed front matter line: ${frontMatter.line}`,
    );
  }
  const fields = new Map(frontMatter.fields.map((field) => [field.key, field.value]));
  const title = fields.get('title');
  if (title === undefined || title === '') return defectOf(path, 'has no title');
  const readWhen = fields.get('read-when');
  if (readWhen === undefined || readWhen === '') {
    return defectOf(path, 'has no read-when');
  }
  const problem = judgeReadWhen(readWhen);
  if (problem !== undefined) return defectOf(path, `read-when ${problem}`);
  return { entry: { name: title, path, readWhen } };
}

/** The defects of one indexed `project.json`, at `path` relative to `root`. */
export function readProjectDefects(root: string, path: string): SourceDefect[] {
  return readProject(root, path).flatMap((reading) =>
    'defect' in reading ? [reading.defect] : [],
  );
}

/**
 * Reads every Nx project (`project.json` under `apps/` and `libs/`) and every authored page
 * (Markdown under `wiki/` outside `wiki/index/`). Never throws for a defect in them; each one is
 * returned, sorted by path.
 */
export function readIndexSources(root: string): IndexSources {
  const readings: Reading[] = [];
  for (const top of ['apps', 'libs']) {
    if (!existsSync(join(root, top))) {
      readings.push(defectOf(top, 'directory is missing'));
      continue;
    }
    for (const path of listFiles(root, top)) {
      if (posix.basename(path) === 'project.json') readings.push(...readProject(root, path));
    }
  }
  for (const path of listMarkdownFiles(root)) {
    if (!path.startsWith('wiki/') || path.startsWith(`${indexDirectory}/`)) continue;
    readings.push(readPage(path, readFileSync(join(root, path), 'utf8')));
  }
  return {
    entries: readings.flatMap((reading) => ('entry' in reading ? [reading.entry] : [])),
    defects: readings
      .flatMap((reading) => ('defect' in reading ? [reading.defect] : []))
      .sort((left, right) => compareBytes(left.path, right.path)),
  };
}

/**
 * The full contents of `wiki/index/`, keyed by path relative to the repository root. Lines are
 * sorted bytewise; the text has LF endings and carries no dates or absolute paths.
 */
export function renderIndex(
  entries: readonly ReadWhenEntry[],
  commands: readonly CommandBrief[],
): Map<string, string> {
  const readWhen = entries
    .map(
      (entry) =>
        `- ${entry.readWhen}: [${entry.name}](${posix.relative(indexDirectory, entry.path)})`,
    )
    .sort(compareBytes);
  const commandLines = [...commands]
    .sort((left, right) => compareBytes(left.path, right.path))
    .map((command) => `- \`${command.path}\`: ${command.brief}`);
  const lines = [
    notice,
    '',
    '# Wiki index',
    '',
    '## Read when',
    '',
    ...readWhen,
    '',
    '## Commands',
    '',
    ...commandLines,
    '',
  ];
  return new Map([[indexFile, lines.join('\n')]]);
}

/** How the committed `wiki/index/` differs from what would be generated; sorted by path. */
export interface IndexDrift {
  readonly missing: readonly string[];
  readonly stale: readonly string[];
  readonly unexpected: readonly string[];
}

/** Compares the committed `wiki/index/` under `root` with `expected`. */
export function compareIndex(root: string, expected: ReadonlyMap<string, string>): IndexDrift {
  const present = existsSync(join(root, indexDirectory)) ? listFiles(root, indexDirectory) : [];
  const expectedPaths = [...expected.keys()].sort(compareBytes);
  return {
    missing: expectedPaths.filter((path) => !present.includes(path)),
    stale: expectedPaths.filter(
      (path) =>
        present.includes(path) && readFileSync(join(root, path), 'utf8') !== expected.get(path),
    ),
    unexpected: present.filter((path) => !expected.has(path)).sort(compareBytes),
  };
}

function removeEmptyDirectories(root: string, directory: string): void {
  for (const entry of readdirSync(join(root, directory), { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const path = posix.join(directory, entry.name);
    removeEmptyDirectories(root, path);
    if (readdirSync(join(root, path)).length === 0) rmSync(join(root, path), { recursive: true });
  }
}

/**
 * Runs `wiki index` against the repository found from `context.cwd`: writes every missing or
 * stale file, removes every file under `wiki/index/` it did not generate, and returns 0. A defect
 * in the repository's inputs, or a repository whose `puni.json` declares a `this-repo-type`
 * other than `system-state`, writes nothing, prints one `error: ` line to `stderr` and returns 1.
 */
export function runWikiIndex(context: WikiIndexContext): 0 | 1 {
  let repository: Repository;
  try {
    repository = findRepository(context.cwd);
  } catch (cause) {
    if (!(cause instanceof RepositoryDefect)) throw cause;
    context.stderr(`error: ${cause.message}\n`);
    return 1;
  }
  if (repository.type !== 'system-state') {
    const file = join(repository.root, 'puni.json');
    context.stderr(
      `error: wiki index needs the system-state repository; ${file} declares this-repo-type ${repository.type}\n`,
    );
    return 1;
  }
  const { root } = repository;
  const sources = readIndexSources(root);
  if (sources.defects.length > 0) {
    const named = sources.defects.map((defect) => `${defect.path}: ${defect.message}`);
    context.stderr(`error: ${named.join('; ')}\n`);
    return 1;
  }
  const expected = renderIndex(sources.entries, context.commands);
  const drift = compareIndex(root, expected);
  mkdirSync(join(root, indexDirectory), { recursive: true });
  const written = [...drift.missing, ...drift.stale].sort(compareBytes);
  for (const path of written) {
    const content = expected.get(path);
    if (content === undefined) throw new Error(`${path} was compared but not rendered`);
    writeFileSync(join(root, path), content);
  }
  for (const path of drift.unexpected) rmSync(join(root, path));
  removeEmptyDirectories(root, indexDirectory);
  const changes = [
    ...written.map((path) => `wrote: ${path}`),
    ...drift.unexpected.map((path) => `removed: ${path}`),
  ];
  context.stdout(
    changes.length === 0 ? `${indexDirectory} is current.\n` : `${changes.join('\n')}\n`,
  );
  return 0;
}
