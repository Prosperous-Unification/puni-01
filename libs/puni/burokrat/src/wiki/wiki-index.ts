import { constant, message, object, option } from '@optique/core';
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, posix, resolve } from 'node:path';

/**
 * `wiki index [--check]`: without `--check` it rewrites `wiki/index/`; with it, it only compares.
 */
export const wikiIndexParser = object({
  kind: constant('wiki index'),
  check: option('--check', {
    description: message`Write nothing; fail when the committed index differs.`,
  }),
});

/** One command of the CLI tree: its full canonical path, such as `puni burokrat`, and brief. */
export interface CommandBrief {
  readonly path: string;
  readonly brief: string;
}

/** What `wiki index` needs from the app that composes it. */
export interface WikiIndexContext {
  /** Where the repository search starts. */
  readonly cwd: string;
  /** Every command of the composed CLI; the burokrat library cannot see the whole tree. */
  readonly commands: readonly CommandBrief[];
  readonly stdout: (text: string) => void;
}

/** The generated directory, relative to the repository root. */
export const indexDirectory = 'wiki/index';

const wikiDirectory = 'wiki';
const notice = '<!-- Generated by `puni burokrat wiki index`. Do not edit. -->';

/**
 * The nearest directory at or above `cwd` that holds an `nx.json`.
 *
 * @throws Error when no such directory exists up to the filesystem root.
 */
export function findRepositoryRoot(cwd: string): string {
  let directory = resolve(cwd);
  for (;;) {
    if (existsSync(join(directory, 'nx.json'))) return directory;
    const parent = dirname(directory);
    if (parent === directory) throw new Error(`no nx.json in ${cwd} or any directory above it`);
    directory = parent;
  }
}

function compareBytes(left: string, right: string): number {
  return Buffer.compare(Buffer.from(left), Buffer.from(right));
}

/** Files under `directory`, relative to `root`, recursively; `node_modules` is never entered. */
function listFiles(root: string, directory: string): string[] {
  return readdirSync(join(root, directory), { withFileTypes: true }).flatMap((entry) => {
    const path = posix.join(directory, entry.name);
    if (entry.isDirectory()) return entry.name === 'node_modules' ? [] : listFiles(root, path);
    return entry.isFile() ? [path] : [];
  });
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

interface Project {
  readonly name: string;
  readonly directory: string;
  readonly description: string;
}

/**
 * Every Nx project under `apps/` and `libs/`, read from its `project.json`.
 *
 * @throws Error naming the file when `name` or `metadata.description` is missing or empty.
 */
function readProjects(root: string): Project[] {
  return ['apps', 'libs']
    .flatMap((top) => listFiles(root, top))
    .filter((path) => posix.basename(path) === 'project.json')
    .map((path) => {
      const parsed: unknown = JSON.parse(readFileSync(join(root, path), 'utf8'));
      if (!isRecord(parsed)) throw new Error(`${path} is not a JSON object`);
      const name = parsed['name'];
      if (typeof name !== 'string' || name === '') throw new Error(`${path} has no name`);
      const metadata = parsed['metadata'];
      const description = isRecord(metadata) ? metadata['description'] : undefined;
      if (typeof description !== 'string' || description.trim() === '') {
        throw new Error(`project ${name} (${path}) has no metadata.description`);
      }
      return { name, directory: posix.dirname(path), description: description.trim() };
    });
}

interface Page {
  readonly path: string;
  readonly title: string;
  readonly readWhen: string;
}

/**
 * The `title` and `read-when` of an authored page, from front matter that opens the file between
 * two `---` lines and holds one `key: value` per line.
 *
 * @throws Error naming the page when the front matter is absent, unclosed or malformed, or
 *   lacks either key.
 */
function readPage(path: string, text: string): Page {
  const lines = text.split(/\r?\n/u);
  const end = lines.indexOf('---', 1);
  if (lines[0] !== '---' || end < 0)
    throw new Error(`page ${path} does not begin with front matter`);
  const fields = new Map<string, string>();
  for (const line of lines.slice(1, end)) {
    const field = /^([A-Za-z][\w-]*):(.*)$/u.exec(line);
    if (field?.[1] === undefined || field[2] === undefined) {
      throw new Error(`page ${path} has a malformed front matter line: ${line}`);
    }
    fields.set(field[1], field[2].trim());
  }
  const title = fields.get('title');
  if (title === undefined || title === '') throw new Error(`page ${path} has no title`);
  const readWhen = fields.get('read-when');
  if (readWhen === undefined || readWhen === '') throw new Error(`page ${path} has no read-when`);
  return { path, title, readWhen };
}

/** Authored pages: Markdown under `wiki/` outside `wiki/index/`. No `wiki/` means no pages. */
function readPages(root: string): Page[] {
  if (!existsSync(join(root, wikiDirectory))) return [];
  return listFiles(root, wikiDirectory)
    .filter((path) => path.endsWith('.md') && !path.startsWith(`${indexDirectory}/`))
    .map((path) => readPage(path, readFileSync(join(root, path), 'utf8')));
}

function linkFromIndex(target: string): string {
  return posix.relative(indexDirectory, target);
}

function renderFile(title: string, lines: readonly string[]): string {
  return [notice, '', `# ${title}`, '', ...lines, ''].join('\n');
}

function countEntries(count: number): string {
  return count === 1 ? '1 entry' : `${String(count)} entries`;
}

/**
 * The full contents of `wiki/index/`, keyed by path relative to `root`. Entries are sorted
 * bytewise by command path, project name or use-case line; the text has LF endings and carries no dates or absolute paths.
 *
 * @throws Error when a project lacks a description or a page lacks `title` or `read-when`.
 */
export function renderWikiIndex(
  root: string,
  commands: readonly CommandBrief[],
): Map<string, string> {
  const modules = readProjects(root)
    .sort((left, right) => compareBytes(left.name, right.name))
    .map(
      (project) =>
        `- [${project.name}](${linkFromIndex(project.directory)}): ${project.description}`,
    );
  const commandLines = [...commands]
    .sort((left, right) => compareBytes(left.path, right.path))
    .map((command) => `- \`${command.path}\`: ${command.brief}`);
  const useCases = readPages(root)
    .map((page) => `- ${page.readWhen}: [${page.title}](${linkFromIndex(page.path)})`)
    .sort(compareBytes);
  const entry = [
    ...(useCases.length === 0 ? [] : ['## Use cases', '', ...useCases, '']),
    '## Catalogue',
    '',
    `- [commands.md](commands.md): every \`puni\` command with its brief; ${countEntries(commandLines.length)}.`,
    `- [modules.md](modules.md): every Nx project under \`apps/\` and \`libs/\` with its description; ${countEntries(modules.length)}.`,
  ];
  return new Map([
    [`${indexDirectory}/commands.md`, renderFile('Commands', commandLines)],
    [`${indexDirectory}/index.md`, renderFile('Wiki index', entry)],
    [`${indexDirectory}/modules.md`, renderFile('Modules', modules)],
  ]);
}

/** How the committed `wiki/index/` differs from what would be generated; sorted by path. */
interface IndexDrift {
  readonly missing: readonly string[];
  readonly stale: readonly string[];
  readonly unexpected: readonly string[];
}

function compareIndex(root: string, expected: ReadonlyMap<string, string>): IndexDrift {
  const present = existsSync(join(root, indexDirectory)) ? listFiles(root, indexDirectory) : [];
  const expectedPaths = [...expected.keys()].sort(compareBytes);
  return {
    missing: expectedPaths.filter((path) => !present.includes(path)),
    stale: expectedPaths.filter(
      (path) =>
        present.includes(path) && readFileSync(join(root, path), 'utf8') !== expected.get(path),
    ),
    unexpected: present.filter((path) => !expected.has(path)).sort(compareBytes),
  };
}

/**
 * Runs `wiki index` against the repository found from `context.cwd`. Without `check` it writes
 * every missing or stale file and removes every file it did not generate, then returns 0. With
 * `check` it writes nothing, names each missing, stale or unexpected file and returns 1 when
 * there is any, else 0.
 *
 * @throws Error when no repository root is found or the sources are invalid; see
 *   {@link renderWikiIndex}.
 */
export function runWikiIndex(
  request: { readonly check: boolean },
  context: WikiIndexContext,
): 0 | 1 {
  const root = findRepositoryRoot(context.cwd);
  const expected = renderWikiIndex(root, context.commands);
  const drift = compareIndex(root, expected);
  const changes = [
    ...drift.missing.map((path) => `missing: ${path}`),
    ...drift.stale.map((path) => `stale: ${path}`),
    ...drift.unexpected.map((path) => `unexpected: ${path}`),
  ];
  if (changes.length === 0) {
    context.stdout(`${indexDirectory} is current.\n`);
    return 0;
  }
  if (request.check) {
    context.stdout(`${changes.join('\n')}\nRun \`puni burokrat wiki index\` to regenerate.\n`);
    return 1;
  }
  mkdirSync(join(root, indexDirectory), { recursive: true });
  const written = [...drift.missing, ...drift.stale].sort(compareBytes);
  for (const path of written) {
    const content = expected.get(path);
    if (content === undefined) throw new Error(`${path} was compared but not rendered`);
    writeFileSync(join(root, path), content);
  }
  for (const path of drift.unexpected) rmSync(join(root, path));
  removeEmptyDirectories(root, indexDirectory);
  context.stdout(
    [
      ...written.map((path) => `wrote: ${path}`),
      ...drift.unexpected.map((path) => `removed: ${path}`),
      '',
    ].join('\n'),
  );
  return 0;
}

function removeEmptyDirectories(root: string, directory: string): void {
  for (const entry of readdirSync(join(root, directory), { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const path = posix.join(directory, entry.name);
    removeEmptyDirectories(root, path);
    if (readdirSync(join(root, path)).length === 0) rmSync(join(root, path), { recursive: true });
  }
}
