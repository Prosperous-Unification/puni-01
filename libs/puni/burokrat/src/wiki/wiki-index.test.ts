import { afterEach, beforeEach, describe, expect, test } from 'bun:test';
import {
  appendFileSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import {
  type CommandBrief,
  findRepositoryRoot,
  indexDirectory,
  renderWikiIndex,
  runWikiIndex,
} from './wiki-index';

const commands: readonly CommandBrief[] = [
  { path: 'puni dash', brief: 'Do it.' },
  { path: 'puni burokrat wiki', brief: 'Wiki.' },
  { path: 'puni burokrat', brief: 'Judge.' },
];

let root = '';

function writeRepositoryFile(path: string, content: string): void {
  mkdirSync(dirname(join(root, path)), { recursive: true });
  writeFileSync(join(root, path), content);
}

function writeProject(directory: string, name: string, description?: string): void {
  const metadata = description === undefined ? {} : { metadata: { description } };
  writeRepositoryFile(`${directory}/project.json`, JSON.stringify({ name, ...metadata }));
}

function runIndex(check: boolean, cwd = root): { code: 0 | 1; printed: string } {
  let printed = '';
  const code = runWikiIndex(
    { check },
    {
      cwd,
      commands,
      stdout: (text) => {
        printed += text;
      },
    },
  );
  return { code, printed };
}

function readIndexFile(name: string): string {
  return readFileSync(join(root, indexDirectory, name), 'utf8');
}

beforeEach(() => {
  root = mkdtempSync(join(tmpdir(), 'puni-wiki-index-'));
  writeRepositoryFile('nx.json', '{}');
  writeProject('apps/puni/cli', 'puni-cli', 'The CLI.');
  writeProject('libs/puni/dash', 'puni-dash', 'Dash commands.');
  writeRepositoryFile('libs/node_modules/stray/project.json', '{}');
});

afterEach(() => {
  rmSync(root, { recursive: true, force: true });
});

describe('findRepositoryRoot', () => {
  test('walks up to the nearest nx.json', () => {
    mkdirSync(join(root, 'apps/puni/cli/src'), { recursive: true });
    expect(findRepositoryRoot(join(root, 'apps/puni/cli/src'))).toBe(resolve(root));
  });

  test('throws when no directory above has an nx.json', () => {
    rmSync(join(root, 'nx.json'));
    expect(() => findRepositoryRoot(root)).toThrow(/no nx\.json/u);
  });
});

describe('renderWikiIndex', () => {
  test('lists projects and commands sorted, with no use cases when there are no pages', () => {
    const files = renderWikiIndex(root, commands);
    expect([...files.keys()]).toEqual([
      'wiki/index/commands.md',
      'wiki/index/index.md',
      'wiki/index/modules.md',
    ]);
    expect(files.get('wiki/index/modules.md')).toBe(
      [
        '<!-- Generated by `puni burokrat wiki index`. Do not edit. -->',
        '',
        '# Modules',
        '',
        '- [puni-cli](../../apps/puni/cli): The CLI.',
        '- [puni-dash](../../libs/puni/dash): Dash commands.',
        '',
      ].join('\n'),
    );
    expect(files.get('wiki/index/commands.md')).toContain(
      '- `puni burokrat`: Judge.\n- `puni burokrat wiki`: Wiki.\n- `puni dash`: Do it.\n',
    );
    const entry = files.get('wiki/index/index.md') ?? '';
    expect(entry).not.toContain('Use cases');
    expect(entry).toContain('commands.md): every `puni` command with its brief; 3 entries.');
    expect(entry).toContain('with its description; 2 entries.');
  });

  test('lists each authored page as a use case, sorted, from any depth under wiki/', () => {
    writeRepositoryFile('wiki/release.md', '---\ntitle: Release\nread-when: Releasing\n---\nBody');
    writeRepositoryFile('wiki/ops/deploy.md', '---\ntitle: Deploy\nread-when: Deploying\n---\n');
    writeRepositoryFile('wiki/notes.txt', 'not a page');
    const entry = renderWikiIndex(root, commands).get('wiki/index/index.md') ?? '';
    expect(entry).toContain(
      '## Use cases\n\n- Deploying: [Deploy](../ops/deploy.md)\n- Releasing: [Release](../release.md)\n\n## Catalogue',
    );
  });

  test('every relative link in every generated file resolves from that file', () => {
    writeRepositoryFile('wiki/ops/deploy.md', '---\ntitle: Deploy\nread-when: Deploying\n---\n');
    const files = renderWikiIndex(root, commands);
    const targets = [...files].flatMap(([path, text]) =>
      [...text.matchAll(/\]\(([^)]+)\)/gu)].map((link) => join(root, dirname(path), link[1] ?? '')),
    );
    for (const [path, text] of files) writeRepositoryFile(path, text);
    expect(targets.length).toBe(5);
    expect(targets.filter((target) => !existsSync(target))).toEqual([]);
  });

  test('output is deterministic, LF-only, free of the root path and opens with the notice', () => {
    const first = renderWikiIndex(root, commands);
    expect(renderWikiIndex(root, [...commands].reverse())).toEqual(first);
    for (const text of first.values()) {
      expect(
        text.startsWith('<!-- Generated by `puni burokrat wiki index`. Do not edit. -->\n'),
      ).toBe(true);
      expect(text).not.toContain('\r');
      expect(text).not.toContain(root);
    }
  });

  test('a project without a description is refused by name', () => {
    writeProject('libs/puni/navigator', 'puni-navigator');
    expect(() => renderWikiIndex(root, commands)).toThrow(
      'project puni-navigator (libs/puni/navigator/project.json) has no metadata.description',
    );
  });

  test.each([
    ['---\ntitle: Deploy\n---\n', 'page wiki/deploy.md has no read-when'],
    ['---\nread-when: Deploying\n---\n', 'page wiki/deploy.md has no title'],
    ['---\ntitle: Deploy\nread-when:\n---\n', 'page wiki/deploy.md has no read-when'],
    ['# Deploy\n', 'page wiki/deploy.md does not begin with front matter'],
    ['---\ntitle: Deploy\n', 'page wiki/deploy.md does not begin with front matter'],
  ])('page %j is refused: %s', (page, reason) => {
    writeRepositoryFile('wiki/deploy.md', page);
    expect(() => renderWikiIndex(root, commands)).toThrow(reason);
  });
});

describe('runWikiIndex', () => {
  test('writes the index from a nested directory, after which --check passes', () => {
    mkdirSync(join(root, 'apps/puni/cli/src'), { recursive: true });
    expect(runIndex(false, join(root, 'apps/puni/cli/src')).code).toBe(0);
    expect(readdirSync(join(root, indexDirectory)).sort()).toEqual([
      'commands.md',
      'index.md',
      'modules.md',
    ]);
    expect(runIndex(true)).toEqual({ code: 0, printed: 'wiki/index is current.\n' });
  });

  test('--check names a stale file, exits 1 and writes nothing', () => {
    runIndex(false);
    appendFileSync(join(root, indexDirectory, 'modules.md'), 'x');
    const stale = readIndexFile('modules.md');
    const run = runIndex(true);
    expect(run.code).toBe(1);
    expect(run.printed).toStartWith('stale: wiki/index/modules.md\n');
    expect(readIndexFile('modules.md')).toBe(stale);
  });

  test('--check names a missing file', () => {
    runIndex(false);
    rmSync(join(root, indexDirectory, 'commands.md'));
    expect(runIndex(true).printed).toStartWith('missing: wiki/index/commands.md\n');
  });

  test('--check names every file in a missing index', () => {
    const run = runIndex(true);
    expect(run.code).toBe(1);
    expect(existsSync(join(root, indexDirectory))).toBe(false);
    expect(run.printed.split('\n').filter((line) => line.startsWith('missing: '))).toHaveLength(3);
  });

  test('--check names an unexpected file; writing removes it', () => {
    runIndex(false);
    writeRepositoryFile('wiki/index/extra/notes.md', 'hand-written');
    expect(runIndex(true)).toEqual({
      code: 1,
      printed:
        'unexpected: wiki/index/extra/notes.md\nRun `puni burokrat wiki index` to regenerate.\n',
    });
    expect(runIndex(false)).toEqual({ code: 0, printed: 'removed: wiki/index/extra/notes.md\n' });
    expect(existsSync(join(root, indexDirectory, 'extra'))).toBe(false);
    expect(runIndex(true).code).toBe(0);
  });

  test('a stale file is rewritten', () => {
    runIndex(false);
    writeRepositoryFile('wiki/index/index.md', 'edited');
    expect(runIndex(false)).toEqual({ code: 0, printed: 'wrote: wiki/index/index.md\n' });
    expect(runIndex(true).code).toBe(0);
  });
});
