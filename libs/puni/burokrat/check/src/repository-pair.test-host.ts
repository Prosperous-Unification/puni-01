/** The rules section of every fixture `AGENTS.md`: the fixture's own, not this repository's. */
export const fixtureAgentsRules =
  '## Rules\n\n1. **Keep the demo small.** It holds only what its\n   tests need.\n2. **Say what broke.** Every failure names its cause.\n';

/** The digest `agents.rules` pins in fixture checks: that of {@link fixtureAgentsRules}. */
export const fixtureAgentsRulesDigest = digestRulesSection(fixtureAgentsRules);

/** The purposes of a fixture repository's partitions: `app`, where its project `one` is. */
export const fixturePurposes: ReadonlyMap<string, string> = new Map([['app', 'changing the app']]);

/**
 * A fixture `puni.json` registering the pair at `rules`, with {@link fixturePurposes} as its map
 * from epoch 2, which introduced it.
 */
export function formatFixtureRegistry(rules: number): string {
  return formatRegistry(
    'system-state',
    fixtureRemotes,
    rules,
    rules >= 2 ? fixturePurposes : new Map(),
  );
}

/** The generated index of a fixture repository at epoch 1, as that epoch's puni wrote it. */
const epochOneIndex: Readonly<Record<string, string>> = {
  'wiki/index/index.md':
    '<!-- Generated by `puni burokrat wiki index`. Do not edit. -->\n\n# Wiki index\n\n## Partitions\n\n- [app](app.md): the projects tagged `scope:app`\n',
  'wiki/index/app.md':
    '<!-- Generated by `puni burokrat wiki index`. Do not edit. -->\n\n# Wiki index: app\n\n## Read when\n\n- changing the one app: [one](../../apps/one/src/index.ts)\n',
};

/** `text` opened by front matter declaring `type` from rules epoch 4, which introduced it. */
function declareAt(epoch: number, type: DocTypeName, text: string): string {
  return epoch >= docTypesEpoch ? declareDocType(text, type) : text;
}

/**
 * Writes the files of the fixture at `root` that the rules epoch `epoch` shapes: `puni.json`
 * pinned there, `AGENTS.md` pointing to the map, and `README.md`. At epoch 1 the pointer is the
 * committed generated index, `index.md` of `wiki/index`; from epoch 2 it is
 * `puni burokrat wiki map`, the generated index removed; from epoch 4 both entry files declare
 * their type: as following the remedies of `repo upgrade` leaves it.
 */
export function writeEpochFiles(root: string, epoch: number): void {
  writeRepositoryFile(root, 'puni.json', formatFixtureRegistry(epoch));
  const pointer = epoch >= 2 ? 'puni burokrat wiki map' : 'wiki/index/index.md';
  writeRepositoryFile(
    root,
    'AGENTS.md',
    declareAt(
      epoch,
      'agents',
      `# demo\n\nStart at \`${pointer}\`. History lives in ${fixtureRemotes['system-records']}, checked out as \`../demo-records\`.\n\n${fixtureAgentsRules}`,
    ),
  );
  writeRepositoryFile(
    root,
    'README.md',
    declareAt(epoch, 'readme', '# demo\n\nRules: [AGENTS.md](AGENTS.md).\n'),
  );
  if (epoch >= 2) {
    removeScratchPath(join(root, 'wiki/index'));
    return;
  }
  for (const [path, text] of Object.entries(epochOneIndex)) writeRepositoryFile(root, path, text);
}

/**
 * Builds a system-state repository named `demo` at `root` that passes every rule of the rules
 * epoch `epoch`, shaped as that epoch's puni leaves it ({@link writeEpochFiles}): `puni.json`,
 * entry files (`AGENTS.md` holding {@link fixtureAgentsRules}), an empty `nx.json`, the CI
 * workflow, the root project `workspace`, one project `one`, and every file staged in a real git
 * repository.
 */
function buildStateRepository(root: string, epoch: number): void {
  mkdirSync(root);
  writeRepositoryFile(root, 'project.json', JSON.stringify({ name: 'workspace' }));
  writeRepositoryFile(root, 'package.json', JSON.stringify({ name: 'demo' }));
  writeProject(root, 'apps/one', 'one', {
    readWhen: 'changing the one app',
    readFirst: 'src/index.ts',
  });
  mkdirSync(join(root, 'libs'));
  writeEpochFiles(root, epoch);
  writeRepositoryFile(root, 'nx.json', '{}');
  symlinkSync('AGENTS.md', join(root, 'CLAUDE.md'));
  writeRepositoryFile(
    root,
    '.github/workflows/ci.yml',
    'on: [push, pull_request]\njobs:\n  gate:\n    steps:\n      - run: bun run gate\n      - run: bun run gate:affected\n',
  );
  runGit(root, ['init', '-q']);
  runGit(root, ['add', '-A']);
}

/**
 * Builds a records repository at `root` that passes every records rule: `AGENTS.md`, declaring
 * its type, the `CLAUDE.md` symlink, and two valid records, the second superseding the first,
 * the first filed before records declared their type and the second declaring it, in a fresh git
 * repository with nothing staged. It holds no `puni.json`: the system-state repository registers
 * it.
 */
function buildRecordsRepository(root: string): void {
  mkdirSync(root);
  writeRepositoryFile(
    root,
    'AGENTS.md',
    '---\npuni-doc-type: agents\n---\n\n# demo records\n\nSee [the plans](nav/plans).\n',
  );
  symlinkSync('AGENTS.md', join(root, 'CLAUDE.md'));
  writeRecord(
    root,
    supersededRecord,
    describeRecord(supersededRecord, { 'superseded-by': supersedingRecord }),
  );
  writeRecord(root, supersedingRecord, {
    'puni-doc-type': 'record',
    ...describeRecord(supersedingRecord, { supersedes: supersededRecord }),
  });
  mkdirSync(join(root, 'dash/anything/deep'), { recursive: true });
  writeRepositoryFile(root, 'dash/anything/deep/notes.txt', 'free form');
  runGit(root, ['init', '-q']);
}

/** A fixture project: a system-state repository and its records repository beside it. */
export interface RepositoryPair {
  readonly state: string;
  readonly records: string;
}

/**
 * A fresh pair in one temporary directory: `demo` (system-state, at the rules epoch `epoch`) and
 * `demo-records` (system-records), each passing every rule of its type. `scratchDirectories`
 * removes both.
 */
export function makeRepositoryPair(
  scratchDirectories: ScratchDirectoryOwner,
  epoch = 1,
): RepositoryPair {
  const parent = scratchDirectories.createDirectory('puni-pair-');
  const pair = { state: join(parent, 'demo'), records: join(parent, 'demo-records') };
  buildStateRepository(pair.state, epoch);
  buildRecordsRepository(pair.records);
  return pair;
}

/** The system-state repository of a fresh {@link makeRepositoryPair}. */
export function makeRepository(scratchDirectories: ScratchDirectoryOwner, epoch = 1): string {
  return makeRepositoryPair(scratchDirectories, epoch).state;
}

/** The records repository of a fresh {@link makeRepositoryPair}. */
export function makeRecordsRepository(scratchDirectories: ScratchDirectoryOwner): string {
  return makeRepositoryPair(scratchDirectories).records;
}

/** Front matter for a fixture record: every required key, valid for `path`, then `extra`. */
export function describeRecord(
  path: string,
  extra: Readonly<Record<string, string>> = {},
): Record<string, string> {
  const kind = recordKinds.find((candidate) => path.startsWith(`${recordDirectories[candidate]}/`));
  if (kind === undefined) throw new Error(`${path} is not in a kind directory`);
  return {
    kind,
    title: 'A fixture record',
    date: posix.basename(path).slice(0, 10),
    commit: 'abc1234',
    topics: 'fixtures, records',
    summary: 'A record the tests build.',
    ...extra,
  };
}

/** Writes a record at `path` whose front matter holds `fields` in order, then a body. */
export function writeRecord(
  root: string,
  path: string,
  fields: Readonly<Record<string, string>>,
  body = 'Body.',
): void {
  const lines = Object.entries(fields).map(([key, value]) => `${key}: ${value}`);
  writeRepositoryFile(root, path, ['---', ...lines, '---', '', body, ''].join('\n'));
}

