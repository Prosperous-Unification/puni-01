import { afterAll, afterEach, beforeEach, describe, expect, test } from 'bun:test';
import {
  chmodSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join } from 'node:path';
import {
  checkoutModule,
  formatRegistry,
  type IndexSources,
  indexFile,
  renderIndex,
  sourceDefectRemedies,
} from '@puni/shared-checkout';
import {
  fixtureRemotes,
  nodeHostModule,
  removeFixture,
  writeProject,
  writeRepositoryFile,
} from '@puni/shared-testing';
import { DiBag } from 'di-bag';
import { burokratWikiModule } from './module';
import { fixtureCommands, makeRepository } from './wiki.test-host';

let root = '';

const readWhenFix = sourceDefectRemedies['read-when'];
const readFirstFix = sourceDefectRemedies['read-first'];

const container = DiBag.createBuilder()
  .withInstalledModules([nodeHostModule, checkoutModule, burokratWikiModule])
  .withServices({ commandCatalog: () => ({ list: () => fixtureCommands }) })
  .buildContainer();

afterAll(async () => {
  await container.close();
});

function readIndexSources(repository: string): IndexSources {
  const files = container.resolve('checkoutFiles').open(repository, 'system-state');
  return container.resolve('checkoutWikiIndex').readSources(files);
}

function runIndex(cwd = root, print = false): { code: number; stdout: string; stderr: string } {
  let stdout = '';
  let stderr = '';
  const code = container.resolve('burokratWikiIndexCommand').run(
    { kind: 'wiki index', print },
    {
      cwd,
      stdout: (text) => {
        stdout += text;
      },
      stderr: (text) => {
        stderr += text;
      },
    },
  );
  return { code, stdout, stderr };
}

function render(): Map<string, string> {
  const sources = readIndexSources(root);
  expect(sources.defects).toEqual([]);
  return renderIndex(sources.entries, fixtureCommands);
}

beforeEach(() => {
  root = makeRepository();
});

afterEach(() => {
  removeFixture(root);
});

describe('renderIndex', () => {
  test('one file: projects and pages merged under Read when, then the commands', () => {
    writeProject(root, 'libs/two', 'two', { readWhen: 'adding to two', readFirst: 'src/index.ts' });
    writeProject(root, 'libs/node_modules/stray', 'stray', {});
    writeRepositoryFile(
      root,
      'wiki/ops/deploy.md',
      '---\ntitle: Deploy\nread-when: deploying\n---\n',
    );
    writeRepositoryFile(root, 'wiki/notes.txt', 'not a page');
    expect(render()).toEqual(
      new Map([
        [
          'wiki/index/index.md',
          [
            '<!-- Generated by `puni burokrat wiki index`. Do not edit. -->',
            '',
            '# Wiki index',
            '',
            '## Read when',
            '',
            '- adding to two: [two](../../libs/two/src/index.ts)',
            '- changing the one app: [one](../../apps/one/src/index.ts)',
            '- deploying: [Deploy](../ops/deploy.md)',
            '',
            '## Commands',
            '',
            '- `demo burokrat`: Judge.',
            '- `demo dash`: Do it.',
            '',
          ].join('\n'),
        ],
      ]),
    );
  });

  test('every relative link resolves from the file that holds it', () => {
    writeRepositoryFile(
      root,
      'wiki/ops/deploy.md',
      '---\ntitle: Deploy\nread-when: deploying\n---\n',
    );
    const targets = [...render()].flatMap(([path, text]) =>
      [...text.matchAll(/\]\(([^)]+)\)/gu)].map((link) => join(root, dirname(path), link[1] ?? '')),
    );
    expect(targets).toHaveLength(2);
    expect(targets.filter((target) => !existsSync(target))).toEqual([]);
  });

  test('output is deterministic, LF-only and free of the root path', () => {
    const sources = readIndexSources(root);
    const first = renderIndex(sources.entries, fixtureCommands);
    expect(renderIndex(sources.entries, [...fixtureCommands].reverse())).toEqual(first);
    for (const text of first.values()) {
      expect(text).not.toContain('\r');
      expect(text).not.toContain(root);
    }
  });
});

describe('readIndexSources', () => {
  test.each([
    [undefined, 'project two has no metadata.readWhen'],
    ['Adding to two', 'project two metadata.readWhen must start with a lower-case letter'],
    ['adding to two.', 'project two metadata.readWhen must not end with a full stop'],
    ['adding\nto two', 'project two metadata.readWhen must be one line'],
    [`adding ${'w '.repeat(20)}`, 'project two metadata.readWhen has 21 words; at most 20'],
    [
      `Adding\n${'w '.repeat(20)}to two.`,
      'project two metadata.readWhen must start with a lower-case letter, must not end with a full stop, must be one line, has 23 words; at most 20',
    ],
  ])('a project with readWhen %j is a defect: %s', (readWhen, message) => {
    writeProject(root, 'libs/two', 'two', { readWhen, readFirst: 'src/index.ts' });
    expect(readIndexSources(root).defects).toEqual([
      { topic: 'read-when', path: 'libs/two/project.json', message },
    ]);
  });

  test.each([
    [undefined, 'is missing'],
    ['src/missing.ts', 'names a missing file'],
    ['src', 'must name a regular file'],
    ['.', 'must stay inside the project'],
    ['../one/src/index.ts', 'must stay inside the project'],
    ['/etc/hostname', 'must be a relative POSIX path'],
  ])('a project with readFirst %j is a defect: %s', (readFirst, problem) => {
    writeProject(root, 'libs/two', 'two', { readWhen: 'adding to two', readFirst });
    expect(readIndexSources(root).defects).toEqual([
      {
        topic: 'read-first',
        path: 'libs/two/project.json',
        message: `project two metadata.readFirst ${problem}`,
      },
    ]);
  });

  test.each([
    ['---\ntitle: Deploy\n---\n', 'has no read-when'],
    ['---\nread-when: deploying\n---\n', 'has no title'],
    ['---\ntitle: Deploy\nread-when:\n---\n', 'has no read-when'],
    [
      '---\ntitle: Deploy\nread-when: Deploying\n---\n',
      'read-when must start with a lower-case letter',
    ],
    ['# Deploy\n', 'does not begin with front matter'],
    ['---\ntitle: Deploy\n', 'does not begin with front matter'],
  ])('page %j is a defect: %s', (page, message) => {
    writeRepositoryFile(root, 'wiki/deploy.md', page);
    expect(readIndexSources(root).defects).toEqual([
      { topic: 'read-when', path: 'wiki/deploy.md', message },
    ]);
  });

  test('a missing libs/ is a defect', () => {
    rmSync(join(root, 'libs'), { recursive: true });
    expect(readIndexSources(root).defects).toEqual([
      { topic: 'read-when', path: 'libs', message: 'directory is missing' },
    ]);
  });
});

describe('wiki index --print', () => {
  test('prints one JSON object, path to content, and writes nothing', () => {
    writeRepositoryFile(root, indexFile, 'edited');
    writeRepositoryFile(root, 'wiki/index/notes.md', 'hand-written');
    const run = runIndex(root, true);
    expect(run).toEqual({
      code: 0,
      stdout: `${JSON.stringify(Object.fromEntries(render()))}\n`,
      stderr: '',
    });
    expect(readFileSync(join(root, indexFile), 'utf8')).toBe('edited');
    expect(existsSync(join(root, 'wiki/index/notes.md'))).toBe(true);
  });

  test('defective inputs print one error line and exit 1', () => {
    writeProject(root, 'libs/two', 'two', {});
    expect(runIndex(root, true)).toEqual({
      code: 1,
      stdout: '',
      stderr: `error: libs/two/project.json: project two has no metadata.readWhen; fix: ${readWhenFix}; libs/two/project.json: project two metadata.readFirst is missing; fix: ${readFirstFix}\n`,
    });
  });
});

describe('the wiki index command', () => {
  test('from a nested directory it removes files it did not generate', () => {
    writeRepositoryFile(root, 'wiki/index/modules.md', 'old partition');
    writeRepositoryFile(root, 'wiki/index/extra/notes.md', 'hand-written');
    expect(runIndex(join(root, 'apps/one/src'))).toEqual({
      code: 0,
      stdout: 'removed: wiki/index/extra/notes.md\nremoved: wiki/index/modules.md\n',
      stderr: '',
    });
    expect(readdirSync(join(root, 'wiki/index'))).toEqual(['index.md']);
    expect(runIndex()).toEqual({ code: 0, stdout: 'wiki/index is current.\n', stderr: '' });
  });

  test('a stale index is rewritten', () => {
    writeRepositoryFile(root, indexFile, 'edited');
    expect(runIndex()).toEqual({ code: 0, stdout: 'wrote: wiki/index/index.md\n', stderr: '' });
  });

  test('a file standing where wiki/index belongs is replaced by the index', () => {
    const expected = readFileSync(join(root, indexFile), 'utf8');
    rmSync(join(root, 'wiki/index'), { recursive: true });
    writeFileSync(join(root, 'wiki/index'), 'a file\n');
    expect(runIndex()).toEqual({
      code: 0,
      stdout: 'wrote: wiki/index/index.md\nremoved: wiki/index\n',
      stderr: '',
    });
    expect(readFileSync(join(root, indexFile), 'utf8')).toBe(expected);
  });

  test('defective inputs print one error line, exit 1 and write nothing', () => {
    writeProject(root, 'libs/two', 'two', {});
    writeRepositoryFile(root, 'wiki/deploy.md', '# Deploy\n');
    const before = readFileSync(join(root, indexFile), 'utf8');
    expect(runIndex()).toEqual({
      code: 1,
      stdout: '',
      stderr: `error: libs/two/project.json: project two has no metadata.readWhen; fix: ${readWhenFix}; libs/two/project.json: project two metadata.readFirst is missing; fix: ${readFirstFix}; wiki/deploy.md: does not begin with front matter; fix: ${readWhenFix}\n`,
    });
    expect(readFileSync(join(root, indexFile), 'utf8')).toBe(before);
  });

  test('no puni.json prints one error line and exits 1', () => {
    rmSync(join(root, 'puni.json'));
    const run = runIndex();
    expect(run.code).toBe(1);
    expect(run.stderr).toMatch(/^error: no puni\.json in [^\n]+\n$/u);
  });

  test('a puni.json declaring another repository type is refused with one error line and exit 1', () => {
    writeRepositoryFile(root, 'puni.json', formatRegistry('system-records', fixtureRemotes));
    const before = readFileSync(join(root, indexFile), 'utf8');
    expect(runIndex()).toEqual({
      code: 1,
      stdout: '',
      stderr: `error: wiki index needs the system-state repository; ${join(root, 'puni.json')} declares this-repo-type system-records\n`,
    });
    expect(readFileSync(join(root, indexFile), 'utf8')).toBe(before);
  });

  test.each([
    [
      'no repository',
      () => {
        rmSync(join(root, '.git'), { recursive: true });
        mkdirSync(join(root, '.git'));
      },
    ],
    [
      'a corrupt index',
      () => {
        writeFileSync(join(root, '.git/index'), 'not an index');
      },
    ],
  ])('a git that cannot list the checkout (%s) is one error line, exit 1', (_name, breakGit) => {
    breakGit();
    writeRepositoryFile(root, indexFile, 'edited');
    const run = runIndex();
    expect([run.code, run.stdout]).toEqual([1, '']);
    expect(run.stderr).toMatch(/^error: git ls-files exited 128: [^\n]+\n$/u);
    expect(readFileSync(join(root, indexFile), 'utf8')).toBe('edited');
  });

  test('a page that cannot be read is one error line naming it, exit 1', () => {
    const page = join(root, 'wiki/deploy.md');
    writeRepositoryFile(root, 'wiki/deploy.md', '---\ntitle: Deploy\nread-when: deploying\n---\n');
    chmodSync(page, 0o000);
    try {
      expect(runIndex()).toEqual({
        code: 1,
        stdout: '',
        stderr: `error: cannot read wiki/deploy.md: EACCES: permission denied, open '${page}'\n`,
      });
    } finally {
      chmodSync(page, 0o600);
    }
  });
});
